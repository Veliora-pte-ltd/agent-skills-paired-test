"""Database helpers: apply SQL migrations to SQLite and dump the schema.

Usage:
    python -m tillroll.db migrate <path-to-sqlite-file>
    python -m tillroll.db dump-schema
"""
from __future__ import annotations

import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / "db" / "migrations"
SCHEMA_FILE = ROOT / "db" / "schema.sql"


def split_migration(text: str) -> tuple[str, str]:
    """Return the (up, down) SQL of a migration file."""
    if "-- +up" not in text or "-- +down" not in text:
        raise ValueError("migration must contain '-- +up' and '-- +down' sections")
    _, rest = text.split("-- +up", 1)
    up, down = rest.split("-- +down", 1)
    return up.strip(), down.strip()


def migration_files() -> list[Path]:
    manifest = json.loads((MIGRATIONS / "manifest.json").read_text())
    return [MIGRATIONS / entry["file"] for entry in manifest["migrations"]]


def migrate(conn: sqlite3.Connection) -> None:
    for path in migration_files():
        up, _ = split_migration(path.read_text())
        conn.executescript(up)


def dump_schema(conn: sqlite3.Connection) -> str:
    rows = conn.execute(
        "SELECT type, name, sql FROM sqlite_master "
        "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type DESC, name"
    ).fetchall()
    lines = ["-- generated by `PYTHONPATH=src python3 -m tillroll.db dump-schema`; do not edit by hand", ""]
    for _type, _name, sql in rows:
        lines.append(sql.strip() + ";")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) >= 1 and argv[0] == "dump-schema":
        conn = sqlite3.connect(":memory:")
        migrate(conn)
        SCHEMA_FILE.write_text(dump_schema(conn))
        print(f"wrote {SCHEMA_FILE.relative_to(ROOT)}")
        return 0
    if len(argv) == 2 and argv[0] == "migrate":
        conn = sqlite3.connect(argv[1])
        migrate(conn)
        conn.commit()
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
