"""Deterministic verifiers. The agent never sees this file.

`verify(task, workdir, basedir)` returns a list of (check_name, passed, detail).
A run passes only if every check passes. `basedir` is an untouched copy of
the task's starting state.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import re
import sqlite3
import subprocess
import tomllib
from pathlib import Path

from tasks import Task

CANONICAL_SECTIONS = ["Breaking", "Added", "Changed", "Deprecated", "Removed", "Fixed", "Security"]
REPO_URL = "https://git.tillroll.example/tillroll/compare/"


# ------------------------------------------------------------------ helpers
def split_migration(text: str) -> tuple[str, str]:
    _, rest = text.split("-- +up", 1)
    up, down = rest.split("-- +down", 1)
    return up.strip(), down.strip()


def dump_schema(conn: sqlite3.Connection) -> str:
    rows = conn.execute(
        "SELECT type, name, sql FROM sqlite_master "
        "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type DESC, name"
    ).fetchall()
    lines = ["-- generated by `PYTHONPATH=src python3 -m tillroll.db dump-schema`; do not edit by hand", ""]
    for _t, _n, sql in rows:
        lines += [sql.strip() + ";", ""]
    return "\n".join(lines)


def schema_state(conn: sqlite3.Connection) -> dict:
    """Structural description of every table and index (independent of SQL text)."""
    state = {}
    for (name,) in conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"):
        cols = [tuple(r[1:]) for r in conn.execute(f"PRAGMA table_info('{name}')")]
        idx = sorted(
            (r[1], r[2], tuple(c[2] for c in conn.execute(f"PRAGMA index_info('{r[1]}')")))
            for r in conn.execute(f"PRAGMA index_list('{name}')")
        )
        fks = sorted(tuple(r[2:5]) for r in conn.execute(f"PRAGMA foreign_key_list('{name}')"))
        state[name] = {"cols": cols, "idx": idx, "fks": fks}
    return state


def apply_files(conn, files: list[Path]) -> None:
    for f in files:
        up, _ = split_migration(f.read_text())
        conn.executescript(up)


def norm(sql: str | None) -> str:
    return re.sub(r"\s+", "", (sql or "")).lower().replace('"', "'")


def today_strings() -> set[str]:
    return {dt.date.today().isoformat(), dt.datetime.now(dt.timezone.utc).date().isoformat()}


# --------------------------------------------------------------- migrations
def verify_migration(task: Task, wd: Path, base: Path) -> list:
    exp = task.expected
    out = []
    add = lambda name, ok, detail="": out.append((name, bool(ok), detail))
    bmig, wmig = base / "db/migrations", wd / "db/migrations"
    base_files = sorted(p.name for p in bmig.glob("*.sql"))
    new_files = sorted(p.name for p in wmig.glob("*.sql") if p.name not in base_files)
    add("one_new_migration_file", len(new_files) == 1, ",".join(new_files))
    if len(new_files) != 1:
        return out
    nf = wmig / new_files[0]
    text = nf.read_text()
    next_id = f"{len(base_files) + 1:04d}"
    add("filename_format", re.fullmatch(rf"{next_id}_[a-z0-9]+(_[a-z0-9]+)*\.sql", nf.name)
        and len(nf.stem) - 5 <= 40, nf.name)
    head = [l.rstrip() for l in text.splitlines()[:3]]
    add("header_lines", head == [f"-- migration: {next_id}", f"-- ticket: {exp['ticket']}", "-- reversible: yes"],
        " | ".join(head))
    has_sections = "-- +up" in text and "-- +down" in text and text.index("-- +up") < text.index("-- +down")
    add("up_down_sections", has_sections)
    changed = [f for f in base_files if (wmig / f).exists() is False
               or (wmig / f).read_bytes() != (bmig / f).read_bytes()]
    add("existing_migrations_untouched", not changed, ",".join(changed))
    # manifest
    try:
        man = json.loads((wmig / "manifest.json").read_text())["migrations"]
        bman = json.loads((bmig / "manifest.json").read_text())["migrations"]
        last = man[-1]
        ok = (man[: len(bman)] == bman and len(man) == len(bman) + 1 and last.get("id") == next_id
              and last.get("file") == nf.name
              and last.get("sha256") == hashlib.sha256(nf.read_bytes()).hexdigest())
        add("manifest_entry", ok, json.dumps(last))
    except Exception as e:  # noqa: BLE001
        add("manifest_entry", False, repr(e))
    if not has_sections:
        return out
    conn = sqlite3.connect(":memory:")
    apply_files(conn, [bmig / f for f in base_files])
    before = schema_state(conn)
    up, down = split_migration(text)
    try:
        conn.executescript(up)
        add("up_applies", True)
    except Exception as e:  # noqa: BLE001
        add("up_applies", False, repr(e))
        return out
    after = schema_state(conn)
    out.extend(task_checks(task, conn, before, after))
    expected_schema = dump_schema(conn)
    try:
        actual = (wd / "db/schema.sql").read_text()
        add("schema_snapshot_regenerated", actual.strip() == expected_schema.strip())
    except FileNotFoundError:
        add("schema_snapshot_regenerated", False, "missing")
    try:
        conn.executescript(down)
        add("down_reverts_exactly", schema_state(conn) == before)
    except Exception as e:  # noqa: BLE001
        add("down_reverts_exactly", False, repr(e))
    return out


def task_checks(task: Task, conn, before: dict, after: dict) -> list:
    exp, out = task.expected, []
    add = lambda name, ok, detail="": out.append((name, bool(ok), detail))
    table = exp["table"]
    if table not in after:
        add("intended_change", False, f"no table {table}")
        return out
    cols = {c[0]: c for c in after[table]["cols"]}  # name, type, notnull, dflt, pk
    new_cols = {n: c for n, c in cols.items()
                if table not in before or n not in {x[0] for x in before[table]["cols"]}}
    if exp["kind"] == "add_column":
        if "column" in exp:
            col = cols.get(exp["column"])
        elif "column_like" in exp:
            col = next((c for n, c in new_cols.items() if exp["column_like"] in n), None)
        else:
            col = next((c for n, c in new_cols.items() if exp["money_like"] in n), None)
        ok = col is not None
        if ok and exp.get("nullable"):
            ok = col[2] == 0
        if ok and "default" in exp:
            ok = norm(col[3]) == norm(exp["default"])
        add("intended_change", ok, repr(col))
        if "money_like" in exp:
            add("money_column_convention", col is not None and col[0].endswith("_minor")
                and col[1].upper() == "INTEGER", repr(col))
    elif exp["kind"] == "create_table":
        fk_col, fk_table = exp["fk"]
        fks = after[table]["fks"]
        ok = fk_col in cols and any(f[0] == fk_table and f[1] == fk_col for f in fks) \
            and any("reason" in n for n in cols)
        add("intended_change", ok, f"cols={list(cols)} fks={fks}")
        money = [c for n, c in cols.items() if exp["money_like"] in n]
        add("money_column_convention", bool(money) and all(c[0].endswith("_minor") and c[1].upper() == "INTEGER"
                                                        for c in money), repr(money))
        ca = cols.get("created_at")
        add("created_at_convention", ca is not None and ca[1].upper() == "TEXT" and ca[2] == 1
            and norm(ca[3]) == norm("strftime('%Y-%m-%dT%H:%M:%fZ', 'now')"), repr(ca))
    elif exp["kind"] == "add_index":
        _name, icols, uniq = exp["index"]
        ok = any(tuple(icols) == i[2] for i in after[table]["idx"] if i not in before[table]["idx"])
        add("intended_change", ok, repr(after[table]["idx"]))
    if "index" in exp:
        name, icols, uniq = exp["index"]
        match = [i for i in after[table]["idx"] if i[2] == tuple(icols)]
        add("index_exists", bool(match) and (not uniq or any(i[1] == 1 for i in match)), repr(match))
        add("index_naming_convention", any(i[0] == name for i in match), repr(match))
    return out


# ----------------------------------------------------------------- releases
def parse_changelog(text: str):
    """Return (preamble, [(heading, body)], link_lines)."""
    lines = text.splitlines()
    links = [l for l in lines if re.match(r"^\[[^\]]+\]: ", l)]
    body = [l for l in lines if l not in links]
    blocks, pre, cur = [], [], None
    for l in body:
        if l.startswith("## "):
            cur = [l, []]
            blocks.append(cur)
        elif cur is None:
            pre.append(l)
        else:
            cur[1].append(l)
    return pre, [(h, "\n".join(b).strip()) for h, b in blocks], links


def sections_of(body: str) -> list[tuple[str, list[str]]]:
    res = []
    for l in body.splitlines():
        m = re.match(r"^###\s+(.*\S)\s*$", l)
        if m:
            res.append((m.group(1), []))
        elif l.strip().startswith("- ") and res:
            res[-1][1].append(l.strip())
    return res


def verify_release(task: Task, wd: Path, base: Path) -> list:
    exp, out = task.expected, []
    add = lambda name, ok, detail="": out.append((name, bool(ok), detail))
    v = exp["version"]
    py = tomllib.loads((wd / "pyproject.toml").read_text())
    add("version_pyproject", py.get("project", {}).get("version") == v, py.get("project", {}).get("version"))
    init = (wd / "src/tillroll/__init__.py").read_text()
    m = re.search(r'__version__\s*=\s*["\']([^"\']+)', init)
    add("version_init", m is not None and m.group(1) == v, m.group(1) if m else None)

    _, bblocks, blinks = parse_changelog((base / "CHANGELOG.md").read_text())
    _, blocks, links = parse_changelog((wd / "CHANGELOG.md").read_text())
    add("changelog_unreleased_empty_on_top", bool(blocks) and blocks[0][0].strip() == "## [Unreleased]"
        and blocks[0][1] == "", blocks[0][0] if blocks else None)
    hd = blocks[1][0].strip() if len(blocks) > 1 else ""
    dates = today_strings()
    add("changelog_release_heading", any(hd == f"## [{v}] - {d}" for d in dates), hd)
    want = sections_of(bblocks[0][1])
    got = sections_of(blocks[1][1]) if len(blocks) > 1 else []
    add("changelog_entries_moved", sorted((s, tuple(e)) for s, e in want) == sorted((s, tuple(e)) for s, e in got),
        repr(got))
    order = [s for s, _ in got]
    add("changelog_section_order", order == exp["sections"], repr(order))
    add("changelog_history_untouched", blocks[2:] == bblocks[1:])
    want_links = {f"[Unreleased]: {REPO_URL}v{v}...HEAD", f"[{v}]: {REPO_URL}v{exp['previous']}...v{v}"}
    old_links = set(blinks) - {l for l in blinks if l.startswith("[Unreleased]")}
    add("changelog_links", want_links <= set(links) and old_links <= set(links), repr(links[:3]))

    rt = wd / "release" / f"{v}.toml"
    try:
        data = tomllib.loads(rt.read_text())
        add("release_file_exists", True)
    except Exception as e:  # noqa: BLE001
        add("release_file_exists", False, repr(e))
        data = {}
    add("release_file_core_fields", data.get("version") == v and data.get("previous") == exp["previous"]
        and data.get("date") in dates and data.get("prerelease") is exp["prerelease"], repr(data))
    add("release_file_bump", data.get("bump") == exp["bump"], repr(data.get("bump")))
    add("release_file_migrations", data.get("migrations") == exp["migrations"]
        and data.get("last_migration") == exp["last_migration"],
        repr((data.get("migrations"), data.get("last_migration"))))
    old = [p.name for p in (base / "release").glob("*.toml")
           if (wd / "release" / p.name).read_bytes() != p.read_bytes()]
    add("previous_release_files_untouched", not old, ",".join(old))
    tags = subprocess.run(["git", "tag"], cwd=wd, capture_output=True, text=True).stdout.split()
    add("no_git_tag_created", tags == ["v1.4.2"], ",".join(tags))
    return out


def verify(task: Task, workdir: Path, basedir: Path) -> list:
    try:
        if task.family == "migration":
            return verify_migration(task, workdir, basedir)
        return verify_release(task, workdir, basedir)
    except Exception as e:  # noqa: BLE001  (a crashed verifier counts as a failed run)
        return [("verifier_error", False, repr(e))]
