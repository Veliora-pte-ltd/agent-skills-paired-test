"""Summarise results/main.jsonl and results/trigger.jsonl into results/summary.json
and results/summary.md. Every number in the article comes from these files.

    python analyse.py
"""
from __future__ import annotations

import json
import math
import random
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
CONDS = ["none", "compact", "comprehensive", "selfgen"]
BOOT = 10_000


def load(name: str) -> list[dict]:
    f = RES / name
    return [json.loads(l) for l in f.read_text().splitlines() if l.strip()] if f.exists() else []


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def pct(xs, q):
    xs = sorted(xs)
    if not xs:
        return math.nan
    i = (len(xs) - 1) * q
    lo, hi = math.floor(i), math.ceil(i)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)


def paired_diff(runs: list[dict], cond: str, metric: str = "passed", seed: int = 1) -> dict:
    """Mean over tasks of (mean metric under cond - mean under none); 95% bootstrap over tasks,
    plus a two-sided sign-flip permutation p-value over tasks."""
    by = defaultdict(lambda: defaultdict(list))
    for r in runs:
        by[r["task"]][r["condition"]].append(float(r[metric]))
    tasks = [t for t in by if by[t].get(cond) and by[t].get("none")]
    d = [st.mean(by[t][cond]) - st.mean(by[t]["none"]) for t in tasks]
    if not d:
        return {}
    rng = random.Random(seed)
    boots = sorted(st.mean(rng.choice(d) for _ in d) for _ in range(BOOT))
    obs = abs(st.mean(d))
    perm = sum(abs(st.mean(x * rng.choice((-1, 1)) for x in d)) >= obs - 1e-12 for _ in range(BOOT)) / BOOT
    return {"diff": st.mean(d), "ci": (pct(boots, 0.025), pct(boots, 0.975)), "p_perm": perm,
            "tasks": len(tasks), "tasks_better": sum(x > 0 for x in d), "tasks_worse": sum(x < 0 for x in d)}


def cell(rs: list[dict]) -> dict:
    n, k = len(rs), sum(r["passed"] for r in rs)
    cost = [r["cost_usd"] for r in rs]
    wall = [r["wall_s"] for r in rs]
    tok_in = [r["usage"]["input"] + r["usage"]["cache_write"] + r["usage"]["cache_read"] for r in rs]
    tok_out = [r["usage"]["output"] for r in rs]
    return {
        "n": n, "passed": k, "pass_rate": k / n if n else math.nan, "wilson": wilson(k, n),
        "mean_score": st.mean(r["score"] for r in rs) if rs else math.nan,
        "cost_total": sum(cost), "cost_mean": st.mean(cost) if rs else math.nan,
        "cost_per_pass": (sum(cost) / k) if k else None,
        "cli_cost_total": sum(r.get("cli_cost_usd") or 0 for r in rs),
        "wall_median": st.median(wall) if rs else math.nan, "wall_p25": pct(wall, .25), "wall_p75": pct(wall, .75),
        "input_tokens_mean": st.mean(tok_in) if rs else math.nan,
        "cache_read_mean": st.mean(r["usage"]["cache_read"] for r in rs) if rs else math.nan,
        "output_tokens_mean": st.mean(tok_out) if rs else math.nan,
        "turns_mean": st.mean(r["num_turns"] or 0 for r in rs) if rs else math.nan,
        "skill_loaded_rate": (sum(bool(r["skill_calls"]) for r in rs) / n) if n else math.nan,
        "errors": sum(1 for r in rs if r.get("is_error") or r.get("exit_code") not in (0, None)),
    }


def right_skill(r: dict) -> bool | None:
    want = "db-migrations" if r["family"] == "migration" else "release"
    if not r["skill_calls"]:
        return None
    return any(want in s for s in r["skill_calls"])


def main() -> None:
    runs = [r for r in load("main.jsonl") if "passed" in r]
    out = {"models": {}, "n_runs": len(runs)}
    md = ["# Summary (generated by analyse.py)", ""]
    for model in sorted({r["model"] for r in runs}):
        mr = [r for r in runs if r["model"] == model]
        m = out["models"][model] = {"conditions": {}, "families": {}, "paired": {}, "checks": {}}
        md += [f"## {model}", "", "| condition | runs | pass rate (95% CI) | mean score | mean cost $ | cost per pass $ | median wall s | mean turns | skill loaded |",
               "|---|---|---|---|---|---|---|---|---|"]
        for c in CONDS:
            rs = [r for r in mr if r["condition"] == c]
            if not rs:
                continue
            x = m["conditions"][c] = cell(rs)
            cpp = f"{x['cost_per_pass']:.4f}" if x["cost_per_pass"] else "n/a"
            md.append(f"| {c} | {x['n']} | {x['pass_rate']:.0%} ({x['wilson'][0]:.0%}–{x['wilson'][1]:.0%}) | "
                      f"{x['mean_score']:.2f} | {x['cost_mean']:.4f} | {cpp} | {x['wall_median']:.1f} | "
                      f"{x['turns_mean']:.1f} | {x['skill_loaded_rate']:.0%} |")
            for fam in ("migration", "release"):
                fr = [r for r in rs if r["family"] == fam]
                m["families"].setdefault(fam, {})[c] = cell(fr)
            if c != "none":
                m["paired"][c] = {"all": paired_diff(mr, c),
                                  "migration": paired_diff([r for r in mr if r["family"] == "migration"], c),
                                  "release": paired_diff([r for r in mr if r["family"] == "release"], c),
                                  "score_all": paired_diff(mr, c, "score"),
                                  "cost_all": paired_diff(mr, c, "cost_usd"),
                                  "wall_all": paired_diff(mr, c, "wall_s")}
                rk = [right_skill(r) for r in rs]
                m["conditions"][c]["right_skill_rate_when_loaded"] = (
                    sum(1 for v in rk if v) / max(1, sum(1 for v in rk if v is not None)))
            fails = Counter(ch["name"] for r in rs for ch in r["checks"] if not ch["ok"])
            m["checks"][c] = dict(fails.most_common())
        md += ["", "Per family pass rate:", "", "| family | " + " | ".join(CONDS) + " |", "|---" * 5 + "|"]
        for fam, d in m["families"].items():
            md.append(f"| {fam} | " + " | ".join(f"{d[c]['pass_rate']:.0%} ({d[c]['passed']}/{d[c]['n']})" if c in d else "" for c in CONDS) + " |")
        md += ["", "Paired difference in pass rate vs none (mean over tasks, 95% bootstrap CI, permutation p):", ""]
        for c, p in m["paired"].items():
            for k in ("all", "migration", "release"):
                q = p[k]
                if q:
                    md.append(f"- {c} / {k}: {q['diff']*100:+.1f} pp ({q['ci'][0]*100:+.1f} to {q['ci'][1]*100:+.1f}), "
                              f"p={q['p_perm']:.3f}, tasks better/worse {q['tasks_better']}/{q['tasks_worse']} of {q['tasks']}")
        md += ["", "Failed checks by condition:", ""]
        for c, f in m["checks"].items():
            md.append(f"- {c}: " + ", ".join(f"{k} {v}" for k, v in f.items()))
        # per task pass counts
        md += ["", "Per task passes:", "", "| task | " + " | ".join(CONDS) + " |", "|---" * 5 + "|"]
        tasks = sorted({r["task"] for r in mr})
        m["per_task"] = {}
        for t in tasks:
            row = {}
            for c in CONDS:
                rs = [r for r in mr if r["task"] == t and r["condition"] == c]
                row[c] = [sum(r["passed"] for r in rs), len(rs)]
            m["per_task"][t] = row
            md.append(f"| {t} | " + " | ".join(f"{row[c][0]}/{row[c][1]}" for c in CONDS) + " |")
        md.append("")
    trig = load("trigger.jsonl")
    if trig:
        out["trigger"] = {}
        md += ["## Trigger test", ""]
        for model in sorted({r["model"] for r in trig}):
            tr = [r for r in trig if r["model"] == model]
            pos = [r for r in tr if r["kind"] == "should_trigger"]
            neg = [r for r in tr if r["kind"] == "should_not_trigger"]
            kp, kn = sum(r["triggered"] for r in pos), sum(r["triggered"] for r in neg)
            out["trigger"][model] = {"pos_n": len(pos), "pos_triggered": kp, "pos_ci": wilson(kp, len(pos)),
                                     "neg_n": len(neg), "neg_triggered": kn, "neg_ci": wilson(kn, len(neg)),
                                     "missed": [r["prompt"] for r in pos if not r["triggered"]],
                                     "false": [r["prompt"] for r in neg if r["triggered"]],
                                     "cost_total": sum(r["cost_usd"] for r in tr)}
            md.append(f"- {model}: triggered on {kp}/{len(pos)} should-trigger prompts; falsely on {kn}/{len(neg)} should-not prompts")
    # Sensitivity check: how much of each result rests on the "CI owns tags" rule alone.
    out["sensitivity_ignore_tag_rule"] = {}
    md += ["", "## Sensitivity: pass rate if the 'no git tag' check is ignored", ""]
    for model in sorted({r["model"] for r in runs}):
        row = out["sensitivity_ignore_tag_rule"][model] = {}
        for c in CONDS:
            rs = [r for r in runs if r["model"] == model and r["condition"] == c and r["family"] == "release"]
            if rs:
                k = sum(all(ch["ok"] for ch in r["checks"] if ch["name"] != "no_git_tag_created") for r in rs)
                row[c] = {"release_passed": k, "release_n": len(rs), "wilson": wilson(k, len(rs))}
                md.append(f"- {model} {c}: release {k}/{len(rs)}")
    # Sensitivity check: the set-aside batch run without a git identity (see PREREGISTRATION.md).
    sens = [r for r in load("discarded-v3-no-git-identity/main.jsonl") if "passed" in r]
    if sens:
        out["sensitivity_no_git_identity"] = {}
        md += ["", "## Sensitivity: set-aside batch without a git identity", ""]
        for model in sorted({r["model"] for r in sens}):
            sr = [r for r in sens if r["model"] == model]
            row = out["sensitivity_no_git_identity"][model] = {}
            for c in CONDS:
                rs = [r for r in sr if r["condition"] == c]
                if rs:
                    row[c] = {"all": cell(rs)}
                    for fam in ("migration", "release"):
                        row[c][fam] = cell([r for r in rs if r["family"] == fam])
                    md.append(f"- {model} {c}: {row[c]['all']['passed']}/{row[c]['all']['n']} "
                              f"(release {row[c]['release']['passed']}/{row[c]['release']['n']}, "
                              f"migration {row[c]['migration']['passed']}/{row[c]['migration']['n']})")
    spend = load("spend.jsonl")
    out["spend"] = {"published_price_total": sum(r["cost_usd"] for r in spend),  # ledger = max(ours, CLI)
                    "by_phase": {}}
    for r in spend:
        out["spend"]["by_phase"][r["phase"]] = out["spend"]["by_phase"].get(r["phase"], 0) + r["cost_usd"]
    out["spend"]["estimates_for_killed_runs"] = sum(r["cost_usd"] for r in spend if r.get("estimate"))
    out["spend"]["cli_reported_total"] = sum(r.get("cli_reported_usd") or 0 for r in spend)
    md += ["", f"Ledger total (higher of our price-list cost and Claude Code's estimate, per run): ${out['spend']['published_price_total']:.2f}"]
    (RES / "summary.json").write_text(json.dumps(out, indent=2, default=float))
    (RES / "summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
